def gamma(lam, n):
    """Number of derangements of [n] with cycle type lam (partition of n, no 1s)."""
    assert sum(lam) == n
    from collections import Counter
    cnt = Counter(lam)
    denom = 1
    for i, m in cnt.items():
        denom *= factorial(m) * i**m
    return factorial(n) // denom


def sgn(lam, n):
    """Sign of a permutation with cycle type lam: (-1)^(n - #cycles)."""
    return (-1) ** (n - len(lam))


if __name__ == "__main__":
    # Verification 1: published P_n(lambda) equals gamma*C / sum(gamma*C)
    for n in sorted(P_published):
        tot = sum(gamma(l, n) * c for l, c in C[n].items())
        ok = all(
            Fraction(gamma(l, n) * C[n][l], tot) == P_published[n][l]
            for l in C[n]
        )
        print(f"n={n}: P_n table check {'OK' if ok else 'FAIL'}")

    # Verification 2: sum_lambda gamma(lambda) C(lambda) * (n-2)! * n! == L_n
    for n in sorted(C):
        tot = sum(gamma(l, n) * c for l, c in C[n].items())
        recon = tot * factorial(n - 2) * factorial(n)
        print(f"n={n}: L_n check {'OK' if recon == L[n] else f'FAIL {recon} vs {L[n]}'}")
